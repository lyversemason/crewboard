// Bundles the server functions (server/*.ts) into supabase/functions/<name>/index.js
// for Supabase's Edge Functions runtime (Deno). Bundling lets them share the
// app's own actions and rules. Run automatically by `npm run db:start`.

import { build } from 'esbuild'

for (const name of ['run-action']) {
  await build({
    entryPoints: [`server/${name}.ts`],
    outfile: `supabase/functions/${name}/index.js`,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    banner: { js: '// Generated by scripts/build-functions.ts from server/. Don’t edit.' },
    logLevel: 'warning',
  })
  console.log(`Built supabase/functions/${name}/index.js`)
}
